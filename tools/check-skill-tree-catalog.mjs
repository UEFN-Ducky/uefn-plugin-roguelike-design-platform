/* Assert skill_tree_catalog.verse matches Progression store.json nodes.
   Run from plugin folder:
     node tools/check-skill-tree-catalog.mjs
   Or with an explicit project:
     node tools/check-skill-tree-catalog.mjs "C:/Users/.../Roguelike"
*/
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const project =
  process.argv[2] ||
  process.env.UEFN_PROJECT ||
  join(process.env.USERPROFILE || '', 'Documents', 'Fortnite Projects', 'Roguelike');

const storePath = join(project, '.ducky', 'roguelike-design', 'store.json');
const catalogPath = join(
  project,
  'Content',
  'Verse',
  'GameDevices',
  'Gameplay',
  'Screens',
  'Hub',
  'skill_tree_catalog.verse',
);

function fail(msg) {
  console.error('FAIL:', msg);
  process.exit(1);
}

if (!existsSync(storePath)) fail('missing store: ' + storePath);
if (!existsSync(catalogPath)) fail('missing catalog: ' + catalogPath);

const store = JSON.parse(readFileSync(storePath, 'utf8'));
const nodes = (((store.progression || {}).tree || {}).nodes) || [];
const verse = readFileSync(catalogPath, 'utf8');

if (!verse.includes('Generated by the Roguelike Design Platform')) {
  fail('catalog missing generated-header marker');
}

const storeIds = nodes.map((n) => String(n.id || '')).filter(Boolean).sort();
const verseIds = [...verse.matchAll(/NodeId\s*:=\s*"([^"]+)"/g)].map((m) => m[1]).sort();

if (storeIds.length !== verseIds.length) {
  fail(`node count mismatch store=${storeIds.length} verse=${verseIds.length}`);
}
for (let i = 0; i < storeIds.length; i++) {
  if (storeIds[i] !== verseIds[i]) {
    fail(`id mismatch at ${i}: store=${storeIds[i]} verse=${verseIds[i]}`);
  }
}

const tw = Number((store.progression.tree || {}).width) || 900;
const th = Number((store.progression.tree || {}).height) || 520;
const wMatch = verse.match(/SkillTreeBoardW\s*<public>\s*:\s*float\s*=\s*([0-9.]+)/);
const hMatch = verse.match(/SkillTreeBoardH\s*<public>\s*:\s*float\s*=\s*([0-9.]+)/);
if (!wMatch || Math.abs(Number(wMatch[1]) - tw) > 0.01) {
  fail(`board width mismatch store=${tw} verse=${wMatch && wMatch[1]}`);
}
if (!hMatch || Math.abs(Number(hMatch[1]) - th) > 0.01) {
  fail(`board height mismatch store=${th} verse=${hMatch && hMatch[1]}`);
}

console.log('OK: skill_tree_catalog.verse matches store.json (' + storeIds.length + ' nodes)');
console.log('project:', project);
