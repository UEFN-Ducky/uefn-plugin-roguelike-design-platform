/* Write Armory (scr_shop_weapons) Verse into the UEFN project from store.json.
   Run from plugin folder:
     node tools/write-armory-verse.mjs
*/
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
const plugin = join(here, '..');
const ui = join(plugin, 'ui', 'js');
const storePath =
  process.env.RGD_STORE ||
  'C:/Users/tas13/Documents/Fortnite Projects/Roguelike/.ducky/roguelike-design/store.json';
const projectRoot =
  process.env.UEFN_PROJECT ||
  'C:/Users/tas13/Documents/Fortnite Projects/Roguelike';

function fail(msg) {
  console.error('FAIL:', msg);
  process.exit(1);
}

const tokensSrc = readFileSync(join(ui, 'rgd', 'ui', '01-tokens.js'), 'utf8');
const modelSrc = readFileSync(join(ui, 'rgd', 'ui', '02-model.js'), 'utf8');
const verseSrc = readFileSync(join(ui, 'rgd', 'ui', '06-verse.js'), 'utf8');

const sandbox = {
  console,
  Math,
  Number,
  String,
  Object,
  Array,
  JSON,
  uid: (p) => p + '_1',
  state: { uiTheme: null },
  result: null,
};
sandbox.global = sandbox;

const harness = `
(function(){
${tokensSrc}
${modelSrc}
${verseSrc}
  global.result = { uiVerseBundle, uiVerseCanvasFile, uiVerseDeviceFile, uiHex6, uiTheme, uiSize, UI_TYPES, UI_BUTTON_STYLE, uiWalk };
})();
`;

try {
  vm.runInNewContext(harness, sandbox, { filename: 'write-armory-harness.js' });
} catch (e) {
  fail('harness eval failed: ' + (e && e.stack ? e.stack : e));
}

if (!sandbox.result || typeof sandbox.result.uiVerseBundle !== 'function') {
  fail('uiVerseBundle missing');
}

if (!existsSync(storePath)) fail('store not found: ' + storePath);
const store = JSON.parse(readFileSync(storePath, 'utf8'));
sandbox.state.uiTheme = store.uiTheme || null;

const screen = (store.uiScreens || []).find((s) => s && s.id === 'scr_shop_weapons');
if (!screen || !screen.root) fail('scr_shop_weapons missing from store');

const bundle = sandbox.result.uiVerseBundle(screen);
const files = [
  { path: bundle.canvasPath, content: bundle.canvasCode },
  { path: bundle.devicePath, content: bundle.deviceCode },
];

const marker = 'Generated by the Roguelike Design Platform';
const written = [];
const skipped = [];
for (const f of files) {
  const abs = join(projectRoot, f.path);
  mkdirSync(dirname(abs), { recursive: true });
  if (existsSync(abs)) {
    const existing = readFileSync(abs, 'utf8');
    if (!existing.includes(marker) && f.path.includes('_ui_device')) {
      /* device is generated without hand-written guards in older files — still overwrite if marker or BuyBtn stale */
    }
    if (existsSync(abs) && !existing.includes(marker) && !f.path.includes('_ui_device')) {
      skipped.push(f.path);
      continue;
    }
  }
  writeFileSync(abs, f.content, 'utf8');
  written.push(f.path);
}

/* Always overwrite device — focus bind must match Armory cards. */
{
  const abs = join(projectRoot, bundle.devicePath);
  writeFileSync(abs, bundle.deviceCode, 'utf8');
  if (!written.includes(bundle.devicePath)) written.push(bundle.devicePath);
}

console.log(JSON.stringify({
  ok: true,
  written,
  skipped,
  binds: (bundle.binds || []).slice(0, 12).map((b) => b.name),
  focusHint: (bundle.deviceCode.match(/SetFocus\(Builder\.(\w+)\)/) || [])[1] || null,
  canvasBytes: bundle.canvasCode.length,
}, null, 2));
